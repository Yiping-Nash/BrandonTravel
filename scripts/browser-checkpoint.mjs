import { chromium } from '../apps/web/node_modules/@playwright/test/index.mjs';
import fs from 'node:fs/promises';
await fs.mkdir('docs/screenshots',{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1512,height:982}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173/?demo=1');
await page.getByTestId('view-board').waitFor();
await page.screenshot({path:'docs/screenshots/checkpoint-1-board.png',fullPage:true});
await page.getByTestId('view-day').click();
await page.screenshot({path:'docs/screenshots/checkpoint-1-day.png',fullPage:true});
await page.getByTestId('view-week').click();
await page.screenshot({path:'docs/screenshots/checkpoint-1-week.png',fullPage:true});
await page.getByTestId('tab-ideas').click();
await page.screenshot({path:'docs/screenshots/checkpoint-1-ideas.png',fullPage:true});
console.log(JSON.stringify({passed:errors.length===0,pageErrors:errors,title:await page.title(),body:(await page.locator('body').innerText()).slice(0,2000)},null,2));
await browser.close();
if(errors.length)process.exitCode=1;
