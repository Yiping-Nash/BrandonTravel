test('calendar native drag and resize persist; invalid drop rolls back; narrow layout usable', async ({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  let s=await(await page.request.post('/api/trips',{data:{title:'日历拖拽验收',destination:'杭州',startDate:'2026-11-02',endDate:'2026-11-06'}})).json();
  s=await(await page.request.post(`/api/trips/${s.trip.id}/commands`,{data:{expectedVersion:s.version,command:{type:'addActivity',activity:{title:'可拖拽的茶歇',date:'2026-11-02',startAt:'2026-11-02T09:00',endAt:'2026-11-02T10:00'}}}})).json();
  const id=s.trip.id,a=s.activities[0];
  const state=async()=>await(await page.request.get(`/api/trips/${id}`)).json();
  await page.goto(`/?trip=${id}`);await page.getByTestId('view-week').click();
  const event=page.getByTestId(`calendar-event-${a.id}`);
  await event.dragTo(page.getByRole('gridcell').nth(48+20)); // Tuesday 10:00
  await expect.poll(async()=>(await state()).activities[0].startAt).toBe('2026-11-03T10:00');
  await expect(event).toContainText('10:00 - 11:00');
  const box=await event.boundingBox();
  await page.mouse.move(box.x+box.width/2,box.y+box.height-1);await page.mouse.down();
  await page.mouse.move(box.x+box.width/2,box.y+box.height+47,{steps:10});await page.mouse.up();
  await expect.poll(async()=>(await state()).activities[0].endAt).toBe('2026-11-03T11:30');
  // Saturday is visible in the seven-day calendar but outside this five-day Trip.
  await event.dragTo(page.getByRole('gridcell').nth(5*48+20));
  await expect(page.getByRole('alert')).toBeVisible();
  expect((await state()).activities[0].date).toBe('2026-11-03');
  await expect(event).toContainText('10:00 - 11:30');
  await page.getByLabel('关闭错误').click();
  await page.reload();await page.getByTestId('view-day').click();await page.getByLabel('选中日期').fill('2026-11-03');
  await expect(event).toContainText('10:00 - 11:30');
  await page.setViewportSize({width:390,height:844});
  await page.getByLabel('收起聊天').click();
  await expect(page.getByTestId('view-day')).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBe(true);
  await page.screenshot({path:'docs/screenshots/e2e-mobile-day.png',fullPage:true,animations:'disabled'});
  expect(errors).toEqual([]);
});
